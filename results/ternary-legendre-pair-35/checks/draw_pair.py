"""Draw the length-35 pair from data/lp35.txt.

Writes data/pair.svg (for the README) and paper/fig_pair.tex (TikZ, for the paper).
With --check, it writes nothing and exits 1 if either file differs from a fresh drawing.

Top: each word as a strip of 35 cells, j = 0, ..., 34.
Bottom: each word on a 5 x 7 grid. Entry j goes to row j mod 5 and to the column of
j mod 7, with the columns in the order 4, 5, 6, 0, 1, 2, 3 (that is, -3, ..., 3).
Since 6j = j (mod 5) and 6j = -j (mod 7), invariance under j -> 6j means that each row
of the grid reads the same from left to right and from right to left.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
cert = {}
for line in (ROOT / "data/lp35.txt").read_text().splitlines():
    if line and not line.startswith("#"):
        k, w = line.split()
        cert[k] = w
COLS = [4, 5, 6, 0, 1, 2, 3]
FILL = {"0": "#E8E8E8", "1": "#56B4E9", "2": "#E69F00"}
TIKZ = {"0": "black!9", "1": "cbblue", "2": "cborange"}


def crt(r, c):
    return next(j for j in range(35) if j % 5 == r and j % 7 == c)


def svg():
    u = 18
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{40 + 35 * u + 20}" height="{4 * u + 30 + 5 * u + 50}" '
           'font-family="Helvetica, Arial, sans-serif" font-size="11">',
           '<rect width="100%" height="100%" fill="white"/>']
    for i, k in enumerate("AB"):
        y = 10 + i * (u + 8)
        out.append(f'<text x="12" y="{y + 13}" font-weight="bold">{k}</text>')
        for j, d in enumerate(cert[k]):
            x = 40 + j * u
            out.append(f'<rect x="{x}" y="{y}" width="{u}" height="{u}" fill="{FILL[d]}" stroke="white"/>')
            out.append(f'<text x="{x + u / 2}" y="{y + 13}" text-anchor="middle">{d}</text>')
    y0 = 10 + 2 * (u + 8) + 22
    out.append(f'<text x="40" y="{y0 - 8}">Row j mod 5, column j mod 7 in the order 4 5 6 0 1 2 3: each row is a palindrome (j → 6j)</text>')
    for i, k in enumerate("AB"):
        x0 = 40 + i * (8 * u + 40)
        out.append(f'<text x="{x0 - 16}" y="{y0 + 13}" font-weight="bold">{k}</text>')
        for r in range(5):
            for ci, c in enumerate(COLS):
                d = cert[k][crt(r, c)]
                x, y = x0 + ci * u, y0 + r * u
                out.append(f'<rect x="{x}" y="{y}" width="{u}" height="{u}" fill="{FILL[d]}" stroke="white"/>')
                out.append(f'<text x="{x + u / 2}" y="{y + 13}" text-anchor="middle">{d}</text>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def tikz():
    out = ["% Generated by checks/draw_pair.py from data/lp35.txt. Do not edit.",
           r"\begin{tikzpicture}[x=3.3mm,y=-3.3mm,every node/.style={font=\scriptsize}]"]
    for i, k in enumerate("AB"):
        y = i * 1.4
        out.append(rf"\node[anchor=east] at (-0.2,{y + 0.5}) {{$\mathbf{{{k}}}$}};")
        for j, d in enumerate(cert[k]):
            out.append(rf"\fill[{TIKZ[d]}] ({j},{y}) rectangle +(0.95,0.95); \node at ({j + 0.475},{y + 0.5}) {{{d}}};")
    y0 = 4.2
    for i, k in enumerate("AB"):
        x0 = 6 + i * 13
        out.append(rf"\node[anchor=east] at ({x0 - 0.2},{y0 + 0.5}) {{$\mathbf{{{k}}}$}};")
        for ci, c in enumerate(COLS):
            out.append(rf"\node at ({x0 + ci + 0.475},{y0 - 0.6}) {{\tiny {c}}};")
        for r in range(5):
            out.append(rf"\node at ({x0 + 7.5},{y0 + r + 0.5}) {{\tiny {r}}};")
            for ci, c in enumerate(COLS):
                d = cert[k][crt(r, c)]
                out.append(rf"\fill[{TIKZ[d]}] ({x0 + ci},{y0 + r}) rectangle +(0.95,0.95); "
                           rf"\node at ({x0 + ci + 0.475},{y0 + r + 0.5}) {{{d}}};")
    out.append(r"\end{tikzpicture}")
    return "\n".join(out) + "\n"


files = {ROOT / "data/pair.svg": svg(), ROOT / "paper/fig_pair.tex": tikz()}
# The drawing itself shows the invariance: every grid row is a palindrome.
assert all(cert[k][crt(r, COLS[c])] == cert[k][crt(r, COLS[6 - c])] for k in "AB" for r in range(5) for c in range(7))
if "--check" in sys.argv:
    diff = [p.name for p, s in files.items() if not p.is_file() or p.read_text() != s]
    print("figure files match a fresh drawing" if not diff else f"figure files differ: {diff}")
    sys.exit(1 if diff else 0)
for p, s in files.items():
    p.write_text(s)
    print(f"wrote {p.relative_to(ROOT)}")
