"""Draw the witness: data/witness.svg (README) and paper/fig_witness.tex (TikZ, paper).

Top: the witness pi as points (j, pi_j) joined in order. Bottom: one arc for each mirror pair
(j, 18 - j), j = 1..8, labelled with pi_j + pi_{18-j}; the two even sums are in orange.
  python3 -I checks/draw_witness.py          write both files
  python3 -I checks/draw_witness.py --check  exit 1 if a file differs from a fresh drawing"""
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
W = [8, 14, 3, 15, 6, 10, 2, 17, 7, 12, 1, 16, 5, 11, 4, 13, 9]
n = len(W)
ODD, EVEN = "#4a5a70", "#d9730d"


def low(j):
    """True if pi_j is smaller than its neighbours (its label goes below the point)."""
    nb = [W[i - 1] for i in (j - 1, j + 1) if 1 <= i <= n]
    return all(W[j - 1] < x for x in nb)


def svg():
    dx, dy, x0, ytop = 36, 12, 44, 20
    X = lambda j: x0 + (j - 1) * dx
    Y = lambda v: ytop + (n - v) * dy
    yaxis = Y(0) + 16
    base = yaxis + 26
    width, height = X(n) + 30, base + 18 * (n // 2) + 14
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" font-family="Helvetica, Arial, sans-serif" font-size="12">',
         '<title>The witness permutation of [17] and its mirror-pair sums</title>',
         f'<rect width="{width}" height="{height}" fill="white"/>']
    pts = " ".join(f"{X(j)},{Y(v)}" for j, v in enumerate(W, 1))
    o.append(f'<polyline points="{pts}" fill="none" stroke="#9aa5b1" stroke-width="1.5"/>')
    for j, v in enumerate(W, 1):
        o.append(f'<circle cx="{X(j)}" cy="{Y(v)}" r="4" fill="{ODD}"/>')
        o.append(f'<text x="{X(j)}" y="{Y(v) + 18 if low(j) else Y(v) - 8}" text-anchor="middle" fill="#222">{v}</text>')
    o.append(f'<line x1="{X(1) - 10}" y1="{yaxis}" x2="{X(n) + 10}" y2="{yaxis}" stroke="#222" stroke-width="1"/>')
    for j in range(1, n + 1):
        o.append(f'<text x="{X(j)}" y="{yaxis + 16}" text-anchor="middle" fill="#555">{j}</text>')
    for j in range(1, n // 2 + 1):
        s = W[j - 1] + W[n - j]
        col = EVEN if s % 2 == 0 else ODD
        r = (n + 1 - 2 * j) * dx / 2
        ry = 18 * (n // 2 + 1 - j)
        o.append(f'<path d="M {X(j)} {base} A {r:g} {ry} 0 0 0 {X(n + 1 - j)} {base}" fill="none" stroke="{col}" stroke-width="{2.5 if col == EVEN else 1.2}"/>')
        o.append(f'<text x="{X(9)}" y="{base + ry + 4}" text-anchor="middle" fill="{col}" font-weight="{"bold" if col == EVEN else "normal"}" stroke="white" stroke-width="4" paint-order="stroke">{s}</text>')
    o.append('</svg>')
    return "\n".join(o) + "\n"


def tikz():
    o = ["% Generated by checks/draw_witness.py; do not edit.",
         "\\begin{tikzpicture}[x=0.62cm,y=0.2cm,font=\\footnotesize]",
         "\\definecolor{oddc}{HTML}{4A5A70}\\definecolor{evenc}{HTML}{D9730D}",
         "\\draw[gray!60,line width=0.8pt] " + " -- ".join(f"({j},{v})" for j, v in enumerate(W, 1)) + ";"]
    for j, v in enumerate(W, 1):
        o.append(f"\\fill[oddc] ({j},{v}) circle (2.2pt) node[{'below' if low(j) else 'above'}=1pt,black] {{{v}}};")
    o.append(f"\\draw (0.5,-1.5) -- ({n}.5,-1.5);")
    o.append("\\foreach \\j in {1,...,17} \\node[gray] at (\\j,-3) {\\j};")
    for j in range(1, n // 2 + 1):
        s = W[j - 1] + W[n - j]
        col, lw = ("evenc", "1.4pt") if s % 2 == 0 else ("oddc", "0.5pt")
        depth = 2.6 * (n // 2 + 1 - j)
        o.append(f"\\draw[{col},line width={lw}] ({j},-4.5) .. controls ({j},{-4.5 - 1.33 * depth:.2f}) and ({n + 1 - j},{-4.5 - 1.33 * depth:.2f}) .. ({n + 1 - j},-4.5);")
        o.append(f"\\node[{col},fill=white,inner sep=1pt] at (9,{-4.5 - depth:.2f}) {{{'\\textbf{' + str(s) + '}' if s % 2 == 0 else s}}};")
    o.append("\\end{tikzpicture}")
    return "\n".join(o) + "\n"


files = {root / "data/witness.svg": svg(), root / "paper/fig_witness.tex": tikz()}
if "--check" in sys.argv:
    bad = [str(p) for p, s in files.items() if not p.is_file() or p.read_text() != s]
    print("figures match a fresh drawing" if not bad else f"differs: {bad}")
    sys.exit(1 if bad else 0)
for p, s in files.items():
    p.write_text(s)
print("wrote", ", ".join(str(p.relative_to(root)) for p in files))
