#!/usr/bin/env python3
"""Draw the two 15 x 16 sign matrices (standard library only).

Usage: python3 -I checks/draw.py [--check]
Writes paper/fig_matrices.tex (TikZ) and data/matrices.svg. With --check, compares the
fresh drawing with the files and exits 1 if they differ.
Dark cell = +1, light cell = -1. Highlighted columns: the Sylvester witness
S0 = {0,1,2,4,8,15} and the 6 columns {0,1,2,3,4,12} where U reaches 3/7.
"""
import json, sys

cert = json.load(open("checks/certificate.json"))
U = [[1 if ch == "+" else -1 for ch in r] for r in cert["U"]]
H = [[(-1) ** bin(r & c).count("1") for c in range(16)] for r in range(1, 16)]
panels = [("$\\hat H$ (Sylvester)", H, (0, 1, 2, 4, 8, 15)),
          ("$U$ (Had.16.3 without row 0)", U, (0, 1, 2, 3, 4, 12))]

def tikz():
    out = ["% Generated by checks/draw.py. Do not edit.", "\\begin{tikzpicture}[x=0.28cm,y=0.28cm]"]
    for p, (title, M, S) in enumerate(panels):
        x0 = p * 19
        out.append(f"\\node[anchor=south] at ({x0 + 8},0.4) {{{title}}};")
        for c in S:
            out.append(f"\\fill[orange!60] ({x0 + c - 0.15},0.15) rectangle ({x0 + c + 1.15},{-15.15});")
        for r in range(15):
            for c in range(16):
                col = "black!80" if M[r][c] == 1 else "black!8"
                out.append(f"\\fill[{col}] ({x0 + c + 0.06},{-r - 0.06}) rectangle ({x0 + c + 0.94},{-r - 0.94});")
    out.append("\\end{tikzpicture}")
    return "\n".join(out) + "\n"

def svg():
    s, pad = 14, 6
    W = 2 * 16 * s + 3 * pad * 4
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{15 * s + 40}" '
           f'viewBox="0 0 {W} {15 * s + 40}" font-family="sans-serif" font-size="13">',
           f'<rect width="{W}" height="{15 * s + 40}" fill="white"/>']
    for p, (title, M, S) in enumerate(panels):
        x0 = pad * 4 + p * (16 * s + pad * 4)
        t = title.replace("$\\hat H$", "Ĥ").replace("$U$", "U")
        out.append(f'<text x="{x0 + 8 * s}" y="18" text-anchor="middle">{t}</text>')
        for c in S:
            out.append(f'<rect x="{x0 + c * s - 2}" y="{28 - 2}" width="{s + 4}" height="{15 * s + 4}" fill="#f5b971"/>')
        for r in range(15):
            for c in range(16):
                f = "#333333" if M[r][c] == 1 else "#ebebeb"
                out.append(f'<rect x="{x0 + c * s + 1}" y="{28 + r * s + 1}" width="{s - 2}" height="{s - 2}" fill="{f}"/>')
    out.append("</svg>")
    return "\n".join(out) + "\n"

files = {"paper/fig_matrices.tex": tikz(), "data/matrices.svg": svg()}
if "--check" in sys.argv:
    bad = [f for f, txt in files.items() if open(f).read() != txt]
    print("figures equal a fresh drawing" if not bad else f"figures differ: {bad}")
    sys.exit(1 if bad else 0)
for f, txt in files.items():
    open(f, "w").write(txt)
print("wrote", ", ".join(files))
